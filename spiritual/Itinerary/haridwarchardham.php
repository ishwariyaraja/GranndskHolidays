                  <ul style="text-align: justify;">
                    
<li><b>DAY 01: HARIDWAR – BARKOT (210KMS / 7-8HR)</b></li>
  <p>
    Pickup from Haridwar Railway Station / Dehradun Airport. Drive via Mussoorie and visit Kempty Falls. Lunch is recommended at Kempty as there are limited options ahead. Continue to Barkot. Check in to hotel. Rest of the day free. Overnight stay at Barkot.<br><br>
    <b>About Barkot:</b> Located at the confluence of Yamuna and Tons rivers, known for apple orchards and views of the Bandarpoonch peaks. Popular stop en route to Yamunotri and Gangotri.
  </p>

  <li><b>DAY 02: BARKOT – YAMUNOTRI – BARKOT (36KMS DRIVE + 6KMS TREK EACH SIDE)</b></li>
  <p>
    Early morning drive to Jankichatti/Phoolchatti. Start 6km trek to Yamunotri (on foot, pony, or doli – own cost). On arrival, visit:<br>
    <b>Yamunotri Temple:</b> Built by Maharani Gularia of Jaipur in the 19th century.<br>
    <b>Surya Kund:</b> Thermal springs; pilgrims cook rice as prasad.<br>
    <b>Divya Shila:</b> Sacred rock pillar, worshipped before entering the temple.<br>
    After darshan, return to Barkot for overnight stay.
  </p>

  <li><b>DAY 03: BARKOT – UTTARKASHI (90KMS / 4HR)</b></li>
  <p>
    After breakfast, drive to Uttarkashi. On arrival, visit:<br>
    <b>Vishwanath Temple:</b> Ancient Shiva temple with Akhand Jyoti and trident.<br>
    <b>Shakti Temple:</b> Known for a giant Trishul said to be thrown by Goddess Durga.<br>
    Check in to hotel. Rest of the day at leisure. Overnight stay at Uttarkashi.
  </p>

  <li><b>DAY 04: UTTARKASHI – GANGOTRI – UTTARKASHI (100KMS EACH SIDE)</b></li>
  <p>
    Early morning drive to Gangotri. En route, take a dip at <b>Garam Kund (Gangnani)</b>. Drive via scenic <b>Harsil Valley</b>. At Gangotri:<br>
    <b>Gangotri Temple:</b> Built by Gorkha General Amar Singh Thapa in the 18th century.<br>
    <b>Bhagirathi River:</b> Holy dip and darshan.<br>
    <b>Submerged Shivling:</b> Seen during winters.<br>
    Return to Uttarkashi. Overnight stay.
  </p>

  <li><b>DAY 05: UTTARKASHI – SONPRAYAG / PHATA (220KMS / 8-9HR)</b></li>
  <p>
    After breakfast, drive to Sonprayag via Moolgarh, Lambgoan, and Tilwara. Enjoy views of River Mandakini along the route. Arrive at Sonprayag / Phata. Check in to hotel. Overnight stay.
  </p>

  <li><b>DAY 06: SONPRAYAG / PHATA – KEDARNATH (30KMS BY ROAD + 19KMS TREK)</b></li>
  <p>
    Early morning transfer to Gaurikund (by local jeep – own cost). Trek to Kedarnath (by foot, pony, or doli – own cost). Visit:<br>
    <b>Kedarnath Temple:</b> One of the 12 Jyotirlingas of Lord Shiva. Temple is set against the backdrop of the Kedarnath range. Overnight stay at Kedarnath.
  </p>

  <li><b>DAY 07: KEDARNATH – SONPRAYAG / PHATA (19KMS TREK + 30KMS ROAD)</b></li>
  <p>
    Early morning attend Abhishek ceremony at Kedarnath Temple. Enter the Garbha Griha and touch the idol. After darshan, trek down to Gaurikund and return to Sonprayag / Phata. Overnight stay.
  </p>

  <li><b>DAY 08: SONPRAYAG / PHATA – BADRINATH (215KMS / 7HR)</b></li>
  <p>
    Drive to Badrinath via Joshimath. Check in to hotel. Evening visit:<br>
    <b>Badrinath Temple:</b> One of the Char Dhams located at 3,133 meters.<br>
    <b>Tapt Kund, Narad Kund, Brahma Kapal, Sheshnetra, Charanpaduka, Mata Murti Temple</b><br>
    <b>Mana Village:</b> Last Indian village before Tibet – visit Vyas Gufa, Bhim Pul, Saraswati River source. Overnight stay.
  </p>

  <li><b>DAY 09: BADRINATH – RUDRAPRAYAG / KIRTINAGAR (160-200KMS)</b></li>
  <p>
    Morning darshan at Badrinath Temple and rituals at <b>Brahmakapal</b> (Pind Daan for ancestors). Sightseeing at Mana Village. Later, drive to Rudraprayag / Kirtinagar via Joshimath. Check in and overnight stay.<br><br>
    <b>About Joshimath:</b> Winter seat of Badrinath. Visit <b>Narsingh Temple</b>, where it is believed that when the idol’s arm falls, Badrinath will cease to exist and Bhavishya Badri will be the future pilgrimage.
  </p>

  <li><b>DAY 10: RUDRAPRAYAG / KIRTINAGAR – RISHIKESH – HARIDWAR (135–160KMS / 4–5HR)</b></li>
  <p>
    Drive to Rishikesh. Visit:<br>
    <b>Laxman Jhula, Ram Jhula, Triveni Ghat, Bharat Mandir, Shivananda Ashram</b><br>
    Later continue to Haridwar. Yatra ends with spiritual memories.
  </p>

